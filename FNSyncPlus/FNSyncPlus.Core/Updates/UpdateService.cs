using System.IO;
using System.Text.Json;
using FNSyncPlus.Core.Services;

namespace FNSyncPlus.Core.Updates;

public sealed record UpdateInstallPlan(bool Ready, string Executable, string Arguments, string Reason);

/// <summary>Check result that keeps the verified release, so a later download installs exactly the
/// release that was checked instead of whatever the server serves on the second request.</summary>
public sealed record UpdateCheckOutcome(bool HasUpdate, string Version, string Notes, string Error, VerifiedRelease? Release)
{
    public static UpdateCheckOutcome No(bool hasUpdate, string version, string notes, string error) =>
        new(hasUpdate, version, notes, error, null);
}

/// <summary>
/// UI-facing coordinator for update checks, downloads and gated installation. It owns no UI and no
/// network policy of its own: policy lives in <see cref="UpdateManifestVerifier"/>, safety in
/// <see cref="BackupActivityGate"/>, and filesystem layout in <see cref="VersionedInstallLayout"/>.
///
/// Installation is always delegated to the separate <c>FNSyncPlus.Updater.exe</c> process, because
/// the running program has to exit before its own files are replaced. The handoff is a signed
/// descriptor, never a bare hash from the command line.
/// </summary>
public sealed class UpdateService
{
    public const string UpdaterFileName = "FNSyncPlus.Updater.exe";
    private static readonly JsonSerializerOptions SerializerOptions = new() { WriteIndented = true };

    private readonly UpdateManifestVerifier? _verifier;
    private readonly string _settingsPath;
    private readonly TaskManager? _taskManager;
    private readonly BackupActivityGate? _gate;
    private readonly VersionedInstallLayout? _layout;
    private readonly Action<string>? _log;
    private readonly HttpClient _http;

    /// <param name="verifierOverride">Test seam: a verifier for a key pair generated by the test.
    /// Production always uses the pinned key; passing this from the app would defeat the pinning
    /// guarantee, so it exists only for the attack-matrix tests.</param>
    /// <param name="httpHandler">Test seam for the loopback HTTPS server. Production leaves it null
    /// and uses the platform handler with normal certificate validation.</param>
    public UpdateService(UpdateSettings settings, string settingsPath, string installRoot, TaskManager? taskManager = null,
        Action<string>? log = null, UpdateManifestVerifier? verifierOverride = null,
        System.Net.Http.HttpMessageHandler? httpHandler = null)
    {
        _http = httpHandler == null
            ? new HttpClient { Timeout = TimeSpan.FromSeconds(30) }
            : new HttpClient(httpHandler) { Timeout = TimeSpan.FromSeconds(30) };
        Settings = settings ?? throw new ArgumentNullException(nameof(settings));
        _settingsPath = settingsPath ?? throw new ArgumentNullException(nameof(settingsPath));
        _taskManager = taskManager;
        _log = log;
        string keyError = "";
        var verifier = verifierOverride ?? PinnedUpdateKey.TryCreateVerifier(out keyError);
        _verifier = verifier;
        SupportMessage = verifier == null
            ? keyError
            : $"已就绪（通道 {CurrentChannelName}，当前版本 {CurrentVersion}）";
        if (string.IsNullOrWhiteSpace(installRoot))
        {
            _layout = null;
            SupportMessage = "未配置安装目录，自动更新不可用";
            return;
        }
        string? managedRoot = VersionedInstallLayout.TryFindRootFromAppDirectory(installRoot);
        _layout = managedRoot == null ? null : new VersionedInstallLayout(managedRoot);
        if (_layout == null && verifier != null)
            SupportMessage = "当前为免安装（ZIP）运行，只能检查更新，不能原地升级。请使用安装程序版本。";
        if (_layout != null && taskManager != null)
        {
            _gate = new BackupActivityGate(
                hasRunningWork: () => taskManager.HasRunningWork,
                hasRunningOrQueuedWork: () => taskManager.HasRunningOrQueuedWork,
                hasUnclearCommitOrLock: () => taskManager.HasUnclearCommitOrLock,
                enterHold: () => taskManager.TryEnterMaintenanceHold(out var lease, "准备安装更新") ? lease : null,
                saveConfiguration: SaveOrThrowAsync,
                log: Log);
        }
    }

    public UpdateSettings Settings { get; }
    public string SupportMessage { get; }
    public bool CanCheck => _verifier != null;
    public bool CanInstall => _verifier != null && _layout != null && _gate != null;
    public string? InstallRoot => _layout?.Root;
    public string? ActiveVersion => _layout?.ActiveVersion;
    public string? PreviousVersion => _layout?.PreviousVersion;
    public string CurrentChannelName => string.Equals(Settings.Channel, "beta", StringComparison.OrdinalIgnoreCase) ? "Beta" : "Stable";

    public UpdateChannel RequestedChannel => string.Equals(Settings.Channel, "beta", StringComparison.OrdinalIgnoreCase)
        ? UpdateChannel.Beta : UpdateChannel.Stable;

    public static Version CurrentVersion =>
        typeof(UpdateService).Assembly.GetName().Version ?? new Version(0, 4, 0);

    public async Task<UpdateCheckOutcome> CheckAsync(CancellationToken token = default)
    {
        if (_verifier == null) return UpdateCheckOutcome.No(false, "", "", SupportMessage);
        var client = new UpdateClient(_verifier, Settings, _http);
        var result = await client.CheckAsync(CurrentVersion, Identity(), token).ConfigureAwait(false);
        Save();
        return result;
    }

    /// <summary>
    /// Downloads exactly the release that was verified. The URL, size and hash all come from that
    /// signed payload, so a second manifest fetch cannot substitute a different package.
    /// </summary>
    public async Task<(UpdateDownloadResult Result, VerifiedRelease? Release)> DownloadAsync(VerifiedRelease release,
        IProgress<long>? progress = null, CancellationToken token = default)
    {
        ArgumentNullException.ThrowIfNull(release);
        if (_verifier == null) return (new UpdateDownloadResult(false, "", SupportMessage), null);
        var client = new UpdateClient(_verifier, Settings, _http);
        var result = await client.DownloadAsync(release, DownloadDirectory, progress, token).ConfigureAwait(false);
        if (!result.Ok)
        {
            Save();
            return (result, null);
        }
        Settings.StagedVersion = release.Version;
        Save();
        return (result, release with { LocalPackagePath = result.FilePath });
    }

    /// <summary>Non-blocking readiness used to explain why an install is deferred in the UI.</summary>
    public InstallReadiness InspectInstallReadiness()
    {
        if (_gate == null) return new InstallReadiness(InstallDecision.Refuse, SupportMessage);
        return _gate.Inspect();
    }

    /// <summary>
    /// Takes the maintenance hold, waits for running backups, writes the signed handoff descriptor,
    /// and returns a session. The caller must either <see cref="TryStartUpdater"/> or dispose the
    /// session; both paths are explicit so the hold can never be leaked by a silent early return.
    /// </summary>
    public async Task<UpdateInstallSession> BeginInstallAsync(VerifiedRelease release, TimeSpan budget,
        CancellationToken token = default)
    {
        ArgumentNullException.ThrowIfNull(release);
        var refuse = new UpdateInstallPlan(false, "", "", "");
        if (_gate == null || _layout == null)
            return new UpdateInstallSession(new InstallReadiness(InstallDecision.Refuse, SupportMessage),
                refuse with { Reason = SupportMessage }, null, null, Log);

        string updater = Path.Combine(_layout.Root, UpdaterFileName);
        if (!File.Exists(updater))
            return Failed($"安装目录缺少更新器：{updater}");

        if (string.IsNullOrWhiteSpace(release.LocalPackagePath) || !File.Exists(release.LocalPackagePath))
            return Failed("更新包文件不存在，请重新下载");

        // Bind the local file to the signed payload before touching the queue: a corrupted or
        // swapped download must be rejected without pausing a single backup.
        string actualHash;
        long actualSize;
        try
        {
            actualSize = new FileInfo(release.LocalPackagePath).Length;
            actualHash = UpdatePackageExtractor.HashFile(release.LocalPackagePath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return Failed($"无法读取更新包：{ex.Message}");
        }
        if (actualSize != release.Size)
            return Failed($"更新包大小与已签名清单不一致（期望 {release.Size}，实际 {actualSize}），拒绝安装");
        if (!string.Equals(actualHash, release.Sha256, StringComparison.OrdinalIgnoreCase))
            return Failed("更新包 SHA-256 与已签名清单不一致，拒绝安装");

        var attempt = await _gate.TryAcquireAsync(budget, token).ConfigureAwait(false);
        if (!attempt.Granted)
        {
            // The gate already released whatever it took; this session holds nothing.
            return new UpdateInstallSession(attempt.Readiness, refuse with { Reason = attempt.Readiness.Reason },
                null, null, Log);
        }

        string descriptorPath = DescriptorPath(release.Version);
        try
        {
            release.ToDescriptor().Save(descriptorPath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            attempt.Lease!.Release();
            return new UpdateInstallSession(new InstallReadiness(InstallDecision.Refuse,
                $"写入更新交接描述失败，已恢复备份：{ex.Message}"), refuse, null, null, Log);
        }

        string arguments = $"--layout \"{_layout.Root}\" --apply --release \"{descriptorPath}\" " +
                           $"--wait-pid {Environment.ProcessId} --wait-seconds 180";
        var plan = new UpdateInstallPlan(true, updater, arguments, "备份已安全停止，可以安装");
        return new UpdateInstallSession(new InstallReadiness(InstallDecision.Proceed, "备份已安全停止，可以安装"),
            plan, release, attempt.Lease, Log);

        UpdateInstallSession Failed(string reason)
        {
            Log($"安装准备失败：{reason}");
            return new UpdateInstallSession(new InstallReadiness(InstallDecision.Refuse, reason),
                refuse with { Reason = reason }, null, null, Log);
        }
    }

    /// <summary>
    /// Starts the updater, hands the session over and attaches the supervision that guards the
    /// maintenance lease from this point on. If the process cannot start, the session is aborted
    /// so backups resume immediately.
    /// </summary>
    /// <param name="abandonAfter">How long the supervision waits before it first checks on the
    /// updater (the window the main program is expected to exit within).</param>
    public bool TryStartUpdater(UpdateInstallSession session, TimeSpan? abandonAfter, out string error)
    {
        ArgumentNullException.ThrowIfNull(session);
        error = "";
        if (!session.Plan.Ready) { error = session.Plan.Reason; return false; }
        try
        {
            var process = System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo
            {
                FileName = session.Plan.Executable,
                Arguments = session.Plan.Arguments,
                UseShellExecute = false,
                WorkingDirectory = InstallRoot ?? AppContext.BaseDirectory
            });
            if (process == null)
            {
                session.Abort("更新器进程未能启动");
                error = "更新器进程未能启动，已恢复备份任务";
                return false;
            }
            session.RecordUpdaterProcess(process.Id);

            // Supervise the real process: the lease is released only when the watchdog proves
            // the updater gave up. The journal baseline excludes everything written before this
            // handoff, so historical lines cannot be mistaken for this attempt's outcome.
            string journalPath = _layout?.JournalPath ?? "";
            long journalBaseline = 0L;
            try { if (File.Exists(journalPath)) journalBaseline = new FileInfo(journalPath).Length; }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
            var watchdog = new ProcessHandoffWatchdog(
                updaterStillRunning: () =>
                {
                    try { return !process.HasExited; }
                    catch (Exception) { return false; } // handle gone: treat as exited
                },
                journalTail: () => ReadJournalTail(journalPath, journalBaseline),
                onConfirmedAbandon: reason => session.ConfirmHandoffAbandoned(reason),
                log: Log,
                initialDelay: abandonAfter ?? TimeSpan.FromMinutes(2));
            session.CommitHandOff(watchdog);
            return true;
        }
        catch (Exception ex) when (ex is System.ComponentModel.Win32Exception or InvalidOperationException or IOException)
        {
            session.Abort($"更新器启动失败：{ex.Message}");
            error = $"更新器启动失败，已恢复备份任务：{ex.Message}";
            return false;
        }
    }

    private static string ReadJournalTail(string journalPath, long baseline)
    {
        if (string.IsNullOrEmpty(journalPath) || !File.Exists(journalPath) || baseline < 0) return "";
        using var stream = new FileStream(journalPath, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);
        if (stream.Length <= baseline) return "";
        stream.Seek(baseline, SeekOrigin.Begin);
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    public string DescriptorPath(string version) =>
        Path.Combine(_layout?.Root ?? Path.GetTempPath(), ".pending", $"release-{version}.json");

    /// <summary>
    /// Acceptance seam: starts a REAL handoff from an already-signed descriptor on disk,
    /// re-verifying it with the exact rules the standalone updater applies (pinned key, version
    /// newer than installed, package inside the install root, size and hash from the signed
    /// manifest). The caller then starts the updater and requests the application exit through
    /// the lifecycle coordinator — the same sequence the unattended scheduler uses.
    ///
    /// Only reachable from the isolated-session handoff probe; production always goes through
    /// CheckAsync/DownloadAsync, so a caller can never inject its own release.
    /// </summary>
    public async Task<(UpdateInstallSession? Session, string Error)> BeginHandoffFromDescriptorAsync(
        string descriptorPath, TimeSpan budget, CancellationToken token = default)
    {
        if (_verifier == null || _layout == null || _gate == null) return (null, SupportMessage);
        var descriptor = ReleaseDescriptor.TryLoad(descriptorPath);
        if (descriptor == null) return (null, "发布描述缺失或格式无效");
        var verdict = ReleaseHandoff.Verify(descriptor, _verifier, CurrentVersion, _layout.Root, DateTimeOffset.UtcNow);
        if (!verdict.Ok || verdict.Release == null) return (null, verdict.Error);
        var verified = verdict.Release with { LocalPackagePath = descriptor.PackagePath };
        var session = await BeginInstallAsync(verified, budget, token).ConfigureAwait(false);
        return session.Plan.Ready ? (session, "") : (session, session.Readiness.Reason);
    }

    /// <summary>Returns an already downloaded, still-valid package for the release, if any.</summary>
    public bool TryFindVerifiedPackage(VerifiedRelease release, out string path)
    {
        path = Path.Combine(DownloadDirectory, $"FN-Sync-Plus-{release.Version}-x64.zip");
        try
        {
            if (!File.Exists(path)) return false;
            var info = new FileInfo(path);
            if (info.Length != release.Size) return false;
            if (!string.Equals(UpdatePackageExtractor.HashFile(path), release.Sha256, StringComparison.OrdinalIgnoreCase))
                return false;
            return true;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { return false; }
    }

    public string DownloadDirectory => Path.Combine(_layout?.Root ?? Path.GetTempPath(), "FNSyncPlus", ".downloads");

    public ClientUpdateIdentity Identity() => new(Settings.MachineGroup, Settings.ReleaseBatch);

    public void Save()
    {
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(_settingsPath))!);
            File.WriteAllText(_settingsPath, JsonSerializer.Serialize(Settings, SerializerOptions));
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // A settings write failure must not break the caller; the UI surfaces the next check result.
        }
    }

    /// <summary>Write that reports failure. An install must not proceed when the configuration that
    /// records the pending update could not be persisted.</summary>
    private void SaveOrThrow()
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(_settingsPath))!);
        File.WriteAllText(_settingsPath, JsonSerializer.Serialize(Settings, SerializerOptions));
    }

    private Task SaveOrThrowAsync()
    {
        SaveOrThrow();
        return Task.CompletedTask;
    }

    private void Log(string message)
    {
        _log?.Invoke(message);
        try
        {
            _layout?.Journal(message);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
    }

    public static UpdateSettings LoadSettings(string path)
    {
        try
        {
            if (File.Exists(path))
                return JsonSerializer.Deserialize<UpdateSettings>(File.ReadAllText(path)) ?? new UpdateSettings();
        }
        catch (Exception ex) when (ex is IOException or JsonException or UnauthorizedAccessException) { }
        return new UpdateSettings();
    }
}
